"""Sanity checks of the airport metrics against known facts.

Writes docs/sanity_checks.md (used in DESIGN.md). Run: python -m airport_agent.sanity_checks
"""
from pathlib import Path

import pandas as pd

from .data_loader import (airports_without_delay_data, build_airport_metrics, delay_window,
                         load_delays)

OUT_FILE = Path(__file__).parent.parent / "docs" / "sanity_checks.md"
KNOWN_AIRPORTS = ["SFO", "BOS", "LGA", "EWR", "DCA", "ORD", "LAX", "SNA", "ANC", "PBI", "MHT"]
CAPACITY_CONSTRAINED = ["BOS", "LGA", "EWR", "DCA", "ORD"]


def md_table(df: pd.DataFrame, fmt: dict) -> str:
    """Render a DataFrame as a Markdown table (index included)."""
    cols = [df.index.name or ""] + list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for idx, row in df.iterrows():
        cells = [str(idx)] + [fmt.get(c, "{}").format(row[c]) if pd.notna(row[c]) else "n/a"
                              for c in df.columns]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def run_checks(m: pd.DataFrame, national_delay_rate: float) -> list:
    """Each check: (known fact, actual value, passed)."""
    nas_rank = m["nas_delay_rate"].rank(ascending=False)
    nas_median = m["nas_delay_rate"].median()
    top10 = set(nas_rank[nas_rank <= 10].index)
    return [
        ("SFO has the highest NAS delay rate in the US (fog + closely spaced runways)",
         f"rank {nas_rank['SFO']:.0f}, {m.loc['SFO', 'nas_delay_rate']:.3f}", nas_rank["SFO"] == 1),
        ("Known capacity-constrained airports are in the NAS top 10",
         ", ".join(f"{a}: #{nas_rank[a]:.0f}" for a in CAPACITY_CONSTRAINED),
         set(CAPACITY_CONSTRAINED) <= top10),
        ("SNA congestion is regulatory, not physical: NAS rate below national median",
         f"{m.loc['SNA', 'nas_delay_rate']:.3f} vs median {nas_median:.3f}",
         m.loc["SNA", "nas_delay_rate"] < nas_median),
        ("ATL is the largest US airport by enplanements",
         m["enplanements_2025"].idxmax(), m["enplanements_2025"].idxmax() == "ATL"),
        ("National 12-month delay rate ~20-24% (BTS on-time ~76-80%)",
         f"{national_delay_rate:.3f}", 0.18 <= national_delay_rate <= 0.26),
        ("Only US airports in the ranking universe",
         f"{m['state'].isna().sum()} without a US state", m["state"].notna().all()),
        ("PBI has delay data after the DJT alias",
         f"{m.loc['PBI', 'nas_delay_rate']:.3f}", pd.notna(m.loc["PBI", "nas_delay_rate"])),
    ]


def main():
    m = build_airport_metrics()
    delays = load_delays()
    window = delay_window(delays)
    recent = delays[(delays["year"] * 100 + delays["month"]).isin(window)]
    national_delay_rate = recent["arr_del15"].sum() / recent["arr_flights"].sum()

    checks = run_checks(m, national_delay_rate)
    check_rows = ["| Known fact | Actual | Result |", "|---|---|---|"] + [
        f"| {fact} | {actual} | {'PASS' if ok else 'FAIL'} |" for fact, actual, ok in checks]

    known = m.loc[KNOWN_AIRPORTS, ["state", "enplanements_2025", "load_factor_2025",
                                   "momentum_vs_national", "nas_delay_rate", "delay_rate",
                                   "cancel_rate"]]
    known.index.name = "Airport"
    known_fmt = {"state": "{}", "enplanements_2025": "{:,.0f}", "load_factor_2025": "{:.3f}",
                 "momentum_vs_national": "{:+.3f}", "nas_delay_rate": "{:.3f}",
                 "delay_rate": "{:.3f}", "cancel_rate": "{:.3f}"}

    dist_cols = ["load_factor_2025", "momentum_vs_national", "nas_delay_rate"]
    dist = m[dist_cols].quantile([0.05, 0.25, 0.5, 0.75, 0.95]).T
    dist.columns = ["p5", "p25", "median", "p75", "p95"]
    dist.index.name = "Metric"

    text = f"""# Sanity checks

Generated by `python -m airport_agent.sanity_checks`. Universe: {len(m)} US airports with at least 500,000
enplanements in 2025. Delay window: {window[0]}-{window[-1]} ({len(window)} months).
Airports without delay data (shown as missing, never zero): {", ".join(airports_without_delay_data(m))}.

## Checks against known facts

{chr(10).join(check_rows)}

## Key airports

{md_table(known, known_fmt)}

## Metric distribution (used to choose the fixed scoring ranges)

{md_table(dist, {c: "{:.3f}" for c in dist.columns})}
"""
    OUT_FILE.parent.mkdir(exist_ok=True)
    OUT_FILE.write_text(text, encoding="utf-8")
    print(text)
    failed = [fact for fact, _, ok in checks if not ok]
    print("All checks passed." if not failed else f"FAILED: {failed}")


if __name__ == "__main__":
    main()
